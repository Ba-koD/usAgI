pub struct Sha256 {
    state: [u32; 8],
    pending: [u8; 64],
    len: u64,
}

impl Default for Sha256 {
    fn default() -> Self {
        Self {
            state: [0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19],
            pending: [0; 64],
            len: 0,
        }
    }
}

impl Sha256 {
    pub fn update(&mut self, mut bytes: &[u8]) {
        let used = (self.len % 64) as usize;
        self.len += bytes.len() as u64;
        if used != 0 {
            let count = (64 - used).min(bytes.len());
            self.pending[used..used + count].copy_from_slice(&bytes[..count]);
            if used + count < 64 {
                return;
            }
            compress(&mut self.state, &self.pending);
            bytes = &bytes[count..];
        }
        let blocks = bytes.chunks_exact(64);
        self.pending[..blocks.remainder().len()].copy_from_slice(blocks.remainder());
        for block in blocks {
            compress(&mut self.state, block);
        }
    }

    pub fn finish(mut self) -> [u8; 32] {
        let used = (self.len % 64) as usize;
        let mut tail = [0; 128];
        tail[..used].copy_from_slice(&self.pending[..used]);
        tail[used] = 0x80;
        let end = if used < 56 { 64 } else { 128 };
        tail[end - 8..end].copy_from_slice(&self.len.wrapping_mul(8).to_be_bytes());
        for block in tail[..end].chunks_exact(64) {
            compress(&mut self.state, block);
        }
        let mut out = [0; 32];
        for (dest, word) in out.chunks_exact_mut(4).zip(self.state) {
            dest.copy_from_slice(&word.to_be_bytes());
        }
        out
    }

    pub fn finish_hex(self) -> String {
        to_hex(self.finish())
    }
}

fn compress(h: &mut [u32; 8], block: &[u8]) {
    let mut w = [0u32; 64];
    for (i, word) in block.chunks_exact(4).enumerate() {
        w[i] = u32::from_be_bytes([word[0], word[1], word[2], word[3]]);
    }
    for i in 16..64 {
        let s0 = w[i - 15].rotate_right(7) ^ w[i - 15].rotate_right(18) ^ (w[i - 15] >> 3);
        let s1 = w[i - 2].rotate_right(17) ^ w[i - 2].rotate_right(19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16].wrapping_add(s0).wrapping_add(w[i - 7]).wrapping_add(s1);
    }
    let [mut a, mut b, mut c, mut d, mut e, mut f, mut g, mut hh] = h;
    for i in 0..64 {
        let s1 = e.rotate_right(6) ^ e.rotate_right(11) ^ e.rotate_right(25);
        let ch = (e & f) ^ (!e & g);
        let t1 = hh.wrapping_add(s1).wrapping_add(ch).wrapping_add(K[i]).wrapping_add(w[i]);
        let s0 = a.rotate_right(2) ^ a.rotate_right(13) ^ a.rotate_right(22);
        let maj = (a & b) ^ (a & c) ^ (b & c);
        let t2 = s0.wrapping_add(maj);
        hh = g;
        g = f;
        f = e;
        e = d.wrapping_add(t1);
        d = c;
        c = b;
        b = a;
        a = t1.wrapping_add(t2);
    }
    for (x, y) in h.iter_mut().zip([a, b, c, d, e, f, g, hh]) {
        *x = x.wrapping_add(y);
    }
}

pub fn digest(data: &[u8]) -> [u8; 32] {
    let mut sha = Sha256::default();
    sha.update(data);
    sha.finish()
}

pub fn hex(data: &[u8]) -> String {
    to_hex(digest(data))
}

fn to_hex(bytes: [u8; 32]) -> String {
    bytes.iter().map(|b| format!("{b:02x}")).collect()
}

/// 표준 Base64 (패딩 포함)
pub fn base64(bytes: &[u8]) -> String {
    const T: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let n = (chunk[0] as u32) << 16 | (*chunk.get(1).unwrap_or(&0) as u32) << 8 | *chunk.get(2).unwrap_or(&0) as u32;
        out.push(T[(n >> 18) as usize & 63] as char);
        out.push(T[(n >> 12) as usize & 63] as char);
        out.push(if chunk.len() > 1 { T[(n >> 6) as usize & 63] as char } else { '=' });
        out.push(if chunk.len() > 2 { T[n as usize & 63] as char } else { '=' });
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn standard_vectors() {
        assert_eq!(hex(b""), "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855");
        assert_eq!(hex(b"abc"), "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
        assert_eq!(
            hex(b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq"),
            "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1"
        );
        // 블록 경계(55·56·64바이트)와 긴 입력
        assert_eq!(hex(&[b'a'; 55]), "9f4390f8d30c2dd92ec9f095b65e2b9ae9b0a925a5258e241c9f1e910f734318");
        assert_eq!(hex(&[b'a'; 56]), "b35439a4ac6f0948b6d6f9e3c6af0f5f590ce20f1bde7090ef7970686ec6738a");
        assert_eq!(hex(&[b'a'; 64]), "ffe054fe7ae0cb6dc65c3af9b61d5209f439851db43d0ba5997337df154668eb");
        assert_eq!(hex(&vec![b'a'; 1_000_000]), "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0");
    }

    #[test]
    fn base64_padding() {
        assert_eq!(base64(b""), "");
        assert_eq!(base64(b"f"), "Zg==");
        assert_eq!(base64(b"fo"), "Zm8=");
        assert_eq!(base64(b"foo"), "Zm9v");
        assert_eq!(base64(b"foobar"), "Zm9vYmFy");
        assert_eq!(base64(&[0xfb, 0xff, 0xfe]), "+//+");
    }

    #[test]
    fn incremental_hash_matches_standard_vector_across_block_boundaries() {
        let data = vec![b'a'; 1_000_000];
        for chunk_size in [63, 64, 65, 64 * 1024] {
            let mut sha = Sha256::default();
            for chunk in data.chunks(chunk_size) {
                sha.update(chunk);
            }
            assert_eq!(sha.finish_hex(), "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0");
        }
    }
}
